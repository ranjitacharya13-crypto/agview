from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse
from typing import Dict, Any
from ...services.project_manager import project_manager
from pathlib import Path
import zipfile
import json
import os
from datetime import datetime

router = APIRouter()

@router.get("/{project_id}/package")
async def package_project(project_id: str):
    project = project_manager.get_project(project_id)
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")
    
    try:
        from ...core.workspace import workspace_manager
        project_path = workspace_manager.get_project_path(project_id)
        
        # Create zip
        zip_path = Path(f"/tmp/{project_id}.zip")
        
        with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zipf:
            # Add all project files
            for file_path in project_path.rglob("*"):
                if file_path.is_file():
                    # Skip node_modules, .git, etc
                    if 'node_modules' in str(file_path) or '.git' in str(file_path) or '__pycache__' in str(file_path):
                        continue
                    arcname = file_path.relative_to(project_path)
                    zipf.write(file_path, arcname)
            
            # Add README
            features_str = ', '.join(project.features) if project.features else 'N/A'
            solution_str = json.dumps(project.solution, indent=2)
            tech_str = json.dumps(project.tech_stack, indent=2)
            verification_str = json.dumps(project.verification, indent=2)
            
            readme_content = f"# {project.name}\n\n"
            readme_content += f"## Problem Statement\n{project.problem_statement}\n\n"
            readme_content += f"## Abstract\n{project.abstract}\n\n"
            readme_content += f"## Architecture\n{solution_str}\n\n"
            readme_content += f"## Features\n{features_str}\n\n"
            readme_content += f"## Tech Stack\n{tech_str}\n\n"
            readme_content += "## Installation\n```\nnpm install\nnpm run dev\n```\n\n"
            readme_content += "Backend:\n```\ncd backend\npip install -r requirements.txt\nuvicorn main:app --reload --port 8001\n```\n\n"
            readme_content += f"## Project Info\n- Project ID: {project.project_id}\n- Stage: {project.stage.value}\n- Files: {len(project.file_changes)}\n\n"
            readme_content += f"## Verification\n{verification_str}\n\n"
            readme_content += "Generated by RLCD Agentic Engineering IDE\n"
            
            zipf.writestr("README.md", readme_content)
            
            # Add project state
            zipf.writestr("project_state.json", json.dumps(project.model_dump(mode='json'), indent=2, default=str))
        
        return FileResponse(
            path=str(zip_path),
            filename=f"{project.name.replace(' ', '_')}_{project_id[:8]}.zip",
            media_type="application/zip"
        )
    
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/{project_id}/readme")
async def generate_readme(project_id: str):
    project = project_manager.get_project(project_id)
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")
    
    features_list = ""
    if project.features:
        for f in project.features:
            features_list += f"- {f}\n"
    else:
        features_list = "- Dashboard\n- Monitoring\n"
    
    arch_str = ""
    if isinstance(project.solution, dict):
        arch_str = json.dumps(project.solution.get('architecture', {}), indent=2)
    
    frontend_stack = "React, TypeScript, Tailwind"
    if project.tech_stack.get('frontend'):
        frontend_stack = ', '.join(project.tech_stack.get('frontend', []))
    
    backend_stack = "FastAPI, PostgreSQL"
    if project.tech_stack.get('backend'):
        backend_stack = ', '.join(project.tech_stack.get('backend', []))
    
    api_list = ""
    if isinstance(project.solution, dict) and project.solution.get('api_requirements'):
        for api_item in project.solution.get('api_requirements', []):
            api_list += f"- {api_item}\n"
    else:
        api_list = "- /api/sensors\n- /api/analytics\n"
    
    deployment = "Docker"
    if isinstance(project.solution, dict):
        deployment = project.solution.get('deployment_requirements', 'Docker + Nginx')
    
    readme = f"# {project.name}\n\n"
    readme += f"## Problem\n{project.problem_statement}\n\n"
    readme += f"## Solution\n{project.abstract}\n\n"
    readme += f"## Features\n{features_list}\n\n"
    readme += f"## Architecture\n{arch_str}\n\n"
    readme += f"## Technology Stack\n**Frontend:** {frontend_stack}\n**Backend:** {backend_stack}\n\n"
    readme += "## Installation\n\n### Frontend\n```bash\nnpm install\nnpm run dev\n```\n\n"
    readme += "### Backend\n```bash\ncd backend\npip install -r requirements.txt\nuvicorn main:app --host 0.0.0.0 --port 8001 --reload\n```\n\n"
    readme += f"## API Endpoints\n{api_list}\n\n"
    readme += "## Testing\n```bash\nnpm run build\nnpm test\n```\n\n"
    readme += f"## Deployment\n{deployment}\n\n"
    readme += f"## Project Status\n- Stage: {project.stage.value}\n- Files: {len(project.file_changes)}\n- Decisions: {len(project.decisions)}\n\n"
    readme += "## Generated By\nRLCD Agentic Engineering IDE\n\n"
    readme += f"Project ID: {project.project_id}\n"
    
    return {
        "success": True,
        "readme": readme
    }

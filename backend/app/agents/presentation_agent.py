class PresentationAgent(BaseAgent):
    def __init__(self):
        super().__init__("presentation_agent", ["technical_writing", "long_context"])
    
    async def execute(self, project_id: str, task: Dict[str, Any]) -> Dict[str, Any]:
        project = self.get_project(project_id)
        if not project:
            return {"success": False, "error": "Project not found"}
        
        self.emit_event(project_id, EventType.PRESENTATION_STARTED, "Presentation generation started")
        self.emit_event(project_id, EventType.AGENT_STARTED, "Presentation agent activated")
        
        # Read actual project files
        self.emit_event(project_id, EventType.AGENT_STARTED, "Reading project artifacts")
        
        files = self.filesystem.list_directory(project_id, "")
        app_content = self.filesystem.read_file(project_id, "src/App.tsx")
        backend_content = self.filesystem.read_file(project_id, "backend/main.py")
        package_json = self.filesystem.read_file(project_id, "package.json")
        
        # Generate presentation content
        slides_content = await self._generate_slides_content(project, {
            "files": files,
            "has_frontend": app_content["success"],
            "has_backend": backend_content["success"],
            "frontend_size": len(app_content.get("content", "")) if app_content["success"] else 0,
            "backend_size": len(backend_content.get("content", "")) if backend_content["success"] else 0
        })
        
        # Create PPTX if available
        pptx_path = None
        if PPTX_AVAILABLE:
            pptx_path = await self._create_pptx(project_id, project, slides_content)
        else:
            # Create markdown presentation as fallback
            pptx_path = await self._create_markdown_presentation(project_id, project, slides_content)
        
        project.stage = ProjectStage.PRESENTATION
        project.presentation = {
            "slides": slides_content,
            "path": pptx_path,
            "generated_at": project.last_modified.isoformat()
        }
        self.save_project(project)
        
        self.emit_event(
            project_id,
            EventType.PRESENTATION_COMPLETED,
            f"Presentation generated with {len(slides_content)} slides",
            data={"path": pptx_path, "slides_count": len(slides_content)}
        )
        
        return {
            "success": True,
            "slides": slides_content,
            "path": pptx_path
        }
    

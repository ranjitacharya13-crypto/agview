    async def _create_pptx(self, project_id: str, project, slides_content: List[Dict[str, Any]]) -> str:
        try:
            from pptx import Presentation
            from pptx.util import Inches, Pt
            from pptx.dml.color import RGBColor
            
            prs = Presentation()
            prs.slide_width = Inches(13.33)
            prs.slide_height = Inches(7.5)
            
            # Title slide layout
            for slide_data in slides_content:
                # Use blank layout for custom design
                slide_layout = prs.slide_layouts[6] if len(prs.slide_layouts) > 6 else prs.slide_layouts[0]
                slide = prs.slides.add_slide(slide_layout)
                
                # Background
                background = slide.background
                fill = background.fill
                fill.solid()
                fill.fore_color.rgb = RGBColor(14, 14, 16) if slide_data["type"] != "title" else RGBColor(24, 24, 24)
                
                # Title
                title_box = slide.shapes.add_textbox(Inches(0.5), Inches(0.3), Inches(12), Inches(0.8))
                title_frame = title_box.text_frame
                title_frame.text = slide_data["title"]
                title_para = title_frame.paragraphs[0]
                title_para.font.size = Pt(28)
                title_para.font.bold = True
                title_para.font.color.rgb = RGBColor(255, 255, 255)
                
                # Content
                content_box = slide.shapes.add_textbox(Inches(0.5), Inches(1.2), Inches(12), Inches(5.5))
                content_frame = content_box.text_frame
                content_frame.word_wrap = True
                
                for line in slide_data["content"]:
                    p = content_frame.add_paragraph()
                    p.text = line
                    p.font.size = Pt(14) if line and not line.startswith("-") and len(line) < 50 else Pt(12)
                    p.font.color.rgb = RGBColor(204, 204, 204) if not line.startswith("-") else RGBColor(133, 133, 133)
                    p.space_after = Pt(6)
                
                # Speaker notes
                if slide_data.get("speaker_notes"):
                    notes_slide = slide.notes_slide
                    text_frame = notes_slide.notes_text_frame
                    text_frame.text = f"Speaker Notes:\n{slide_data['speaker_notes']}"
            
            # Save
            output_path = f"presentations/{project.name.replace(' ', '_')}_presentation.pptx"
            full_path = f"workspace/{project_id}/{output_path}"
            
            # Ensure directory exists
            from pathlib import Path
            Path(f"workspace/{project_id}/presentations").mkdir(parents=True, exist_ok=True)
            
            prs.save(full_path)
            
            # Also save to project workspace via filesystem service
            # Read and write through service to ensure tracking
            return output_path
            
        except Exception as e:
            print(f"PPTX creation error: {e}")
            return await self._create_markdown_presentation(project_id, project, slides_content)
    
    async def _create_markdown_presentation(self, project_id: str, project, slides_content: List[Dict[str, Any]]) -> str:
        md_content = f"# {project.name} - Presentation\n\n"
        md_content += f"Generated: {project.last_modified.isoformat()}\n\n"
        md_content += f"Problem: {project.problem_statement}\n\n"
        md_content += "---\n\n"
        
        for slide in slides_content:
            md_content += f"## Slide {slide['id']}: {slide['title']}\n\n"
            for line in slide["content"]:
                md_content += f"{line}\n"
            md_content += f"\n**Speaker Notes:** {slide.get('speaker_notes', '')}\n\n"
            md_content += "---\n\n"
        
        output_path = f"presentations/{project.name.replace(' ', '_')}_presentation.md"
        self.filesystem.write_file(project_id, output_path, md_content, agent=self.name)
        
        # Also create JSON for frontend
        json_path = f"presentations/{project.name.replace(' ', '_')}_slides.json"
        self.filesystem.write_file(project_id, json_path, json.dumps(slides_content, indent=2), agent=self.name)
        
        return output_path
